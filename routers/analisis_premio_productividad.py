    candidatos_sin_detalle: list[dict[str, Any]] = []
    detalle_oracle = 0
    detalle_cache = 0
    dias_oracle = 0
    dias_cache = 0

    async with aiosqlite.connect(PREMIO_DB_PATH) as db:
        db.row_factory = aiosqlite.Row
